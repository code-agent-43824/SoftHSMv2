GOST28147::GOST28147() : paramSet(CRYPTOPRO_A), keyed(false)
{
	memset(key, 0, sizeof(key)); loadSBox();
}
GOST28147::~GOST28147()
{
	volatile unsigned char* p = reinterpret_cast<volatile unsigned char*>(key);
	for (size_t i = 0; i < sizeof(key); ++i) p[i] = 0;
}

bool GOST28147::setParamSet(const ByteString& oid)
{
	static const unsigned char base[6]={0x2a,0x85,0x03,0x02,0x02,0x1f};
	static const unsigned char z[9]={0x2a,0x85,0x03,0x07,0x01,0x02,0x05,0x01,0x01};
	const unsigned char* p = oid.const_byte_str();
	if (oid.size()==0) paramSet=CRYPTOPRO_A;
	else if (oid.size()==9 && p[0]==0x06 && p[1]==0x07 && !memcmp(p+2,base,6) && p[8]<=4) paramSet=static_cast<ParamSet>(p[8]);
	else if (oid.size()==11 && p[0]==0x06 && p[1]==0x09 && !memcmp(p+2,z,9)) paramSet=TC26_Z;
	else return false;
	loadSBox(); return true;
}
void GOST28147::loadSBox()
{
	if(paramSet==TC26_Z){memcpy(sbox,zSBox,sizeof(sbox));return;}
	const unsigned char* p=testPacked;
	if(paramSet==CRYPTOPRO_A)p=aPacked; else if(paramSet==CRYPTOPRO_B)p=bPacked; else if(paramSet==CRYPTOPRO_C)p=cPacked; else if(paramSet==CRYPTOPRO_D)p=dPacked;
	for(size_t v=0;v<16;++v)for(size_t b=0;b<8;++b){unsigned char x=p[v*4+b/2];sbox[b][v]=b%2==0?x>>4:x&15;}
}
bool GOST28147::setKey(const unsigned char* p, size_t n)
{
	if (!p || n != 32) return false;
	for (size_t i = 0; i < 8; ++i) key[i] = loadLE32(p + i * 4);
	keyed = true; return true;
}
uint32_t GOST28147::round(uint32_t v) const
{
	uint32_t r = 0;
	for (size_t i = 0; i < 8; ++i)
		r |= (uint32_t)sbox[i][(v >> (4 * i)) & 15] << (4 * i);
	return (r << 11) | (r >> 21);
}
void GOST28147::crypt(const unsigned char in[8],unsigned char out[8],bool dec) const
{
	if (!keyed || !in || !out) return;
	uint32_t n1 = loadLE32(in), n2 = loadLE32(in + 4);
	for (size_t i = 0; i < 32; ++i)
	{
		size_t k = dec ? (i < 8 ? i : 7 - (i % 8)) : (i < 24 ? i % 8 : 7 - (i % 8));
		uint32_t next = n2 ^ round(n1 + key[k]);
		if (i == 31) n2 = next;
		else { n2 = n1; n1 = next; }
	}
	storeLE32(out, n1); storeLE32(out + 4, n2);
}
void GOST28147::encryptBlock(const unsigned char in[8], unsigned char out[8]) const { crypt(in, out, false); }
void GOST28147::decryptBlock(const unsigned char in[8], unsigned char out[8]) const { crypt(in, out, true); }
void GOST28147::macBlock(unsigned char state[8],const unsigned char block[8])const
{
	uint32_t n1 = loadLE32(state) ^ loadLE32(block);
	uint32_t n2 = loadLE32(state + 4) ^ loadLE32(block + 4);
	for (size_t i = 0; i < 16; ++i)
	{
		uint32_t next = n2 ^ round(n1 + key[i % 8]); n2 = n1; n1 = next;
	}
	storeLE32(state, n1); storeLE32(state + 4, n2);
}
void GOST28147::meshKey(unsigned char iv[8])
{
	unsigned char next[32];
	for (size_t i = 0; i < 32; i += 8) decryptBlock(meshConstant + i, next + i);
	setKey(next, 32);
	if (iv)
	{
		unsigned char t[8]; encryptBlock(iv, t); memcpy(iv, t, 8); memset(t, 0, 8);
	}
	memset(next, 0, 32);
}
